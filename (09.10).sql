-- 고객테이블에서 나이가 20세이상 30세 이하인 고객의 고객이름, 나이 ,직업을 출력하시오.
select 고객이름, 나이 ,직업
    from 고객 
    where 나이 >=  20 and 나이 <= 30;
    
