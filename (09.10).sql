select * from 고객;    
--  고객테이블에서 직업이 학생이거나 나이가 26세 이상인 고객의 고객이름, 나이, 직업을 출력하시오.
select 고객이름, 나이, 직업
    from 고객
    where 직업 = '학생' or 나이 >= 26;
    
--  고객테이블에서 직업이 학생이고 나이가 22세 이상인 고객의 고객이름, 나이, 직업을 출력하시오.
select 고객이름, 나이, 직업
    from 고객
    where 직업 = '학생' and 나이 >= 22;

--  제품테이블에서 단가가 2000원 이상이면서 3000원 이하인 제품의 제품명, 단가 ,제조업체를 출력하시오.
select 제품명, 단가, 제조업체
    from 제품
